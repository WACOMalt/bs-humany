describe('the observation', () => {
  it('is, for one fixed state of the reference body, exactly what it was', async () => {
    const { articulation } = compileArticulation(document, 'l3_anatomical', morphology);
    const muscles = compileMuscleSet(
      [...ANKLE_MUSCLES, ...KNEE_MUSCLES],
      document.attachmentSites,
      articulation,
      morphology.context,
      document.wrappingSurfaces ?? [],
    );
    const kernel = new Kernel({ rateHz: 1000, seed: 1 });
    kernel.register(
      new PhysicsModule(new MujocoBackend(), articulation, { ground: { height: 0 } }),
    );
    kernel.register(new PassiveJointModule(articulation));
    kernel.register(
      new MuscleTestDriveModule(muscles, [
        { units: 'all', pattern: { kind: 'constant', level: 0.1 } },
      ]),
    );
    kernel.register(new MusclePathModule(articulation, muscles));
    kernel.register(new MuscleDynamicsModule(articulation, muscles));
    const plantar = muscles.units.filter((u) => /soleus|gastrocnemius/.test(u.id));
    const flexors = muscles.units.filter((u) => /biceps_femoris|semi/.test(u.id));
    const nerves = new NervesModule(articulation, muscles, {
      policy: (inputs, outputs) => new MlpPolicy([inputs, 4, outputs]),
      outputs: [
        { id: 'plantar', units: plantar.map((u) => ({ id: u.id, weight: 1 })) },
        { id: 'flexors', units: flexors.map((u) => ({ id: u.id, weight: 1 })) },
      ],
      goalSize: 2,
      goal: () => [1, 0],
    });
    kernel.register(nerves);
    await kernel.init();
    // A few ticks, so the joints, the contacts and the muscles hold what a running body holds.
    kernel.run(20);

    // Then a pelvis and a head turned well away from upright and spinning, so the rotation into
    // each segment's frame -- the arithmetic most easily reordered by a refactor -- runs on
    // every component rather than on the identity. What it gives back is pinned as it is, not
    // endorsed: as written that rotation returns the vector it was given, to a rounding, so the
    // pinned down is world down and the pinned spins are the world spins scaled (see the note
    // on the rotation in observation.ts). Those last bits of rounding are what a reorder moves.
    const segments = articulation.segments;
    const pelvis = segments.findIndex((s) => s.id === 'pelvis');
    const head = segments.findIndex((s) => s.id === 'head');
    const pose = kernel.channels.storage(BODY_POSE).fields;
    const velocity = kernel.channels.storage(BODY_VELOCITY).fields;
    const orientation = pose.orientation as Float64Array;
    const angular = velocity.angular as Float64Array;
    const linear = velocity.linear as Float64Array;
    const turn = (at: number, x: number, y: number, z: number, w: number): void => {
      const n = Math.hypot(x, y, z, w);
      orientation.set([x / n, y / n, z / n, w / n], 4 * at);
    };
    turn(pelvis, 0.13, -0.21, 0.07, 0.95);
    turn(head, -0.29, 0.11, 0.33, 0.87);
    angular.set([0.7, -1.3, 0.45], 3 * pelvis);
    angular.set([-2.1, 0.6, 1.9], 3 * head);
    linear.set([0.31, -0.12, -0.44], 3 * pelvis);

    const out = new Float64Array(nerves.observation.size);
    nerves.observation.fill(out, [1, 0]);
    expect(out.length).toBe(PINNED.length);
    for (let i = 0; i < PINNED.length; i++) {
      if (!Object.is(out[i], PINNED[i])) {
        expect.fail(`${nerves.observation.names[i]} (${i}) is ${out[i]}, was ${PINNED[i]}`);
      }
    }
  }, 60_000);
});

describe('the feet', () => {
  // Per side: the whole foot at L0; foot and toes at L1; hindfoot, midfoot, forefoot and toes at
  // L2; and at L3 the talus, the calcaneus, the midfoot, the forefoot and fourteen phalanges.
  const PER_SIDE: Record<string, number> = {
    l0_ragdoll: 1,
    l1_standard: 2,
    l2_biomechanical: 4,
    l3_anatomical: 18,
  };

  it('are found on every profile, the same number a side', () => {
    expect(SEGMENTATION_PROFILES.map((p) => p.id).sort()).toEqual(Object.keys(PER_SIDE).sort());
    for (const profile of SEGMENTATION_PROFILES) {
      const { articulation } = compileArticulation(document, profile.id, morphology);
      const feet = feetOf(articulation);
      expect(feet.left.length, profile.id).toBe(PER_SIDE[profile.id]);
      expect(feet.right.length, profile.id).toBe(PER_SIDE[profile.id]);
      // Mirror images: a segment of the left foot is the right foot's with its side swapped.
      expect(feet.right, profile.id).toEqual(feet.left.map((id) => id.replace(/_l$/, '_r')));
    }
  });

  it('are the segments they always were on L0, L1 and L3, and the whole foot on L2', () => {
    // L2 is the profile the anchor match was for: its root foot segment is `hindfoot_`, which
    // the old `foot_`/`talus_` id match missed. Everywhere else nothing may change.
    const at = (id: string) =>
      feetOf(compileArticulation(document, id, morphology).articulation).left;
    expect(at('l0_ragdoll')).toEqual(['foot_l']);
    expect(at('l1_standard')).toEqual(['foot_l', 'toes_l']);
    expect(at('l2_biomechanical')).toEqual(['hindfoot_l', 'midfoot_l', 'forefoot_l', 'toes_l']);
    expect(at('l3_anatomical').slice(0, 4)).toEqual([
      'talus_l',
      'calcaneus_l',
      'midfoot_l',
      'forefoot_l',
    ]);
  });
});
