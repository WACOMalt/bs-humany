/**
 * The companion Blender script.
 *
 * Two rates, and keeping them apart is the point. *Simulation steps per second* is how finely the
 * motion was computed and there is one keyframe for each of them, at its own time in seconds.
 * *Output frame rate* is how finely the Blender timeline is divided, and it is what the scene is
 * set to. A second of simulated time is a second of timeline at any pair of them.
 *
 * So a thousand steps a second into a sixty fps scene puts about seventeen keyframes inside each
 * frame, on fractional frames, and the scene plays at sixty. Nothing is resampled and nothing is
 * thrown away: the curves hold every step, which is what makes them worth rendering at a higher
 * rate later or stepping through by hand. Set the output rate equal to the step rate and every
 * keyframe lands on an integer frame, which is the older behaviour and still available.
 *
 * The rest of what it does is tidying that the format cannot carry. glTF has no way to say "this
 * empty is a joint centre, draw it small and hide it", or "this mesh is a muscle belly, shade it
 * smooth and give it flesh rather than bone"; all of that is Blender's, so it is done here rather
 * than left for whoever opens the file.
 */

export interface BlenderScriptOptions {
  /** File name of the .glb, expected next to the script. */
  readonly glbFileName: string;
  /** Simulation steps per second, which is what sets a keyframe's time. */
  readonly rate: number;
  /** Frames a second of timeline is divided into; becomes the scene's frame rate. */
  readonly outputFramerate: number;
  /** Keyframes written. */
  readonly frames: number;
  /** Recorded samples skipped between keyframes; 1 when every one was kept. */
  readonly stride: number;
  /** Simulation steps the recording held, before the stride. */
  readonly steps: number;
  /** The belly vertex cache, expected next to the script. */
  readonly pointCacheFileName?: string | undefined;
  /** Samples in that cache, one per output frame. */
  readonly pointCacheSamples?: number | undefined;
  /** Each muscle's slice of the joined belly mesh, for naming vertex groups. */
  readonly muscleGroups?:
    | ReadonlyArray<{
        readonly name: string;
        readonly displayName: string;
        readonly start: number;
        readonly count: number;
      }>
    | undefined;
}

/** "2nd", "3rd", "11th": for a sentence that has to read like one. */
function ordinal(n: number): string {
  const tens = n % 100;
  if (tens >= 11 && tens <= 13) return `${n}th`;
  return `${n}${['th', 'st', 'nd', 'rd'][n % 10] ?? 'th'}`;
}

export function blenderImportScript(options: BlenderScriptOptions): string {
  const rate = Math.round(options.rate);
  const fps = Math.max(1, Math.round(options.outputFramerate));
  const stride = Math.max(1, Math.round(options.stride));
  const seconds = options.steps / rate;
  const lastFrame = Math.max(0, Math.round(seconds * fps));
  const perFrame = rate / fps / stride;
  const cache = options.pointCacheFileName;
  const groups = options.muscleGroups ?? [];
  return `# Generated by bs-humany. Run it from Blender's Text Editor, or:
#   blender --python ${options.glbFileName.replace(/\.glb$/, '')}.py
#
# Imports ${options.glbFileName}: ${options.steps} simulation steps at ${rate} a second, which is
# ${seconds.toFixed(3)} seconds, into a ${fps} fps scene -- so frames 0 to ${lastFrame}, with
# ${perFrame === Math.round(perFrame) ? String(perFrame) : perFrame.toFixed(2)} keyframes inside
# each one. A second of simulated time is a second of timeline.
#${
    stride > 1
      ? `
# Every ${ordinal(stride)} step was kept: ${rate} a second into ${fps} fps is more samples inside one
# frame than a frame can show, and a keyframe costs far more in Blender than a sample costs in the
# recording. ${options.frames} keyframes rather than ${options.steps}.`
      : `
# Every step was kept -- ${options.frames} keyframes, nothing resampled.`
  }
#${
    cache
      ? `
# The muscle bellies are one mesh with a PC2 vertex cache, ${cache}, which Blender streams from
# disk through a Mesh Cache modifier. Keep it next to the .glb. They were skinned meshes over
# 3552 armature bones once and that cost 4.3 GB of Blender for six tenths of a second.`
      : ''
  }
#
# If the file is somewhere else, put its full path here and run again.
GLB = ${JSON.stringify(options.glbFileName)}

import os
import bpy

def find_glb():
    """Where the .glb might be, in the order worth trying."""
    if os.path.isabs(GLB):
        return GLB if os.path.isfile(GLB) else None
    roots = []
    # Run with --python, or from the Text Editor in a Blender new enough to set __file__.
    if "__file__" in globals():
        roots.append(os.path.dirname(os.path.abspath(__file__)))
    # Run from the Text Editor: the text block remembers the file it was loaded from.
    for text in bpy.data.texts:
        if text.filepath:
            roots.append(os.path.dirname(bpy.path.abspath(text.filepath)))
    # Next to the .blend, and finally wherever Blender was started.
    if bpy.data.filepath:
        roots.append(os.path.dirname(bpy.path.abspath(bpy.data.filepath)))
    roots.append(os.getcwd())
    for root in roots:
        candidate = os.path.join(root, GLB)
        if os.path.isfile(candidate):
            return candidate
    return None

path = find_glb()
if path is None:
    raise RuntimeError(
        "bs-humany: cannot find " + GLB + ". Save it next to this script, or set GLB at the "
        "top of this file to its full path. Looked in: " + os.getcwd()
    )

scene = bpy.context.scene
# The scene's rate is the output rate, not the step rate. glTF times are in seconds and Blender
# converts them with this, so setting it here before the import is what makes a simulated second
# land on a second of timeline.
scene.render.fps = ${fps}
scene.render.fps_base = 1.0
scene.frame_start = 0
scene.frame_end = ${lastFrame}

before = set(bpy.data.objects)
bpy.ops.import_scene.gltf(filepath=path)
imported = [o for o in bpy.data.objects if o not in before]

# Every joint centre is an empty, and Blender draws an empty one metre across by default: a
# hundred of them makes a thicket of axes that hides the skeleton. They are shrunk to a
# centimetre and moved to their own collection, which starts hidden. Un-hide "Joint centres"
# in the outliner to check a pivot against the bone it turns inside.
joints = bpy.data.collections.new("Joint centres")
scene.collection.children.link(joints)
for ob in imported:
    if ob.type != "EMPTY":
        continue
    ob.empty_display_size = 0.01
    if ob.name.startswith("joint__"):
        ob.empty_display_type = "SPHERE"
        for c in list(ob.users_collection):
            c.objects.unlink(ob)
        joints.objects.link(ob)

layer = bpy.context.view_layer.layer_collection.children.get(joints.name)
if layer is not None:
    layer.hide_viewport = True

# The bellies arrive as one mesh at its first frame and do not move on their own: their movement
# is a PC2 vertex cache beside this file, which a Mesh Cache modifier reads a frame at a time
# from disk. That is the whole reason this import is cheap. Blender holds one frame of it, not
# all of them, and a longer run costs disk rather than memory.
muscles = bpy.data.collections.new("Muscles")
scene.collection.children.link(muscles)

flesh = bpy.data.materials.new("bs-humany muscle")
# A node tree if it does not already have one. Node materials are the only kind from 4.x on and
# a new material arrives with a tree, so this only runs on older Blenders -- which matters because
# use_nodes is deprecated in 5.x and setting it warns. (No backticks anywhere in this script: it
# is written inside a template literal and one would close it.)
if flesh.node_tree is None and hasattr(flesh, "use_nodes"):
    flesh.use_nodes = True
surface = flesh.node_tree.nodes.get("Principled BSDF") if flesh.node_tree else None
if surface is not None:
    surface.inputs["Base Color"].default_value = (0.62, 0.16, 0.16, 1.0)
    roughness = surface.inputs.get("Roughness")
    if roughness is not None:
        roughness.default_value = 0.55

def move_to(ob, collection):
    for c in list(ob.users_collection):
        c.objects.unlink(ob)
    collection.objects.link(ob)

# Which muscle owns which stretch of the joined mesh, so any one of them can be isolated: select
# its vertex group in edit mode, or use it to mask a modifier.
GROUPS = ${JSON.stringify(groups.map((g) => [g.name, g.start, g.count]))}
CACHE = ${cache ? JSON.stringify(cache) : 'None'}

belly = None
for ob in imported:
    if ob.type == "MESH" and ob.name == "muscles":
        belly = ob
        move_to(ob, muscles)
        ob.data.materials.clear()
        ob.data.materials.append(flesh)
        for polygon in ob.data.polygons:
            polygon.use_smooth = True
        # The sweep already gives every ring its own frame, so the seam where the tube closes is
        # the only place two vertices sit on top of each other.
        ob.data.validate()

if belly is not None and GROUPS:
    for name, start, count in GROUPS:
        group = belly.vertex_groups.new(name=name)
        group.add(range(start, start + count), 1.0, "REPLACE")

if belly is not None and CACHE is not None:
    cache_path = os.path.join(os.path.dirname(path), CACHE)
    if os.path.isfile(cache_path):
        modifier = belly.modifiers.new(name="bs-humany bellies", type="MESH_CACHE")
        modifier.cache_format = "PC2"
        modifier.filepath = cache_path
        modifier.forward_axis = "POS_Y"
        modifier.up_axis = "POS_Z"
        modifier.flip_axis = (False, False, False)
        # One sample per frame, starting at frame zero, in the scene's own frames. Absolute
        # positions rather than an offset from the rest shape, which is what PC2 holds.
        modifier.deform_mode = "OVERWRITE"
        modifier.time_mode = "FRAME"
        modifier.play_mode = "SCENE"
        modifier.frame_start = 0.0
        modifier.frame_scale = 1.0
    else:
        print("bs-humany: no vertex cache at", cache_path, "-- the bellies will not move.")

scene.frame_set(0)
print(
    "bs-humany: imported", path,
    "--", ${options.steps}, "simulation steps at", ${rate}, "a second,",
    "over", round(${seconds}, 3), "seconds, into a", ${fps}, "fps scene;",
    ${options.frames}, "keyframes", ${stride > 1 ? `"(every ${ordinal(stride)} step)"` : '"(every step)"'},
)
`;
}
