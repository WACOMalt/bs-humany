#!/usr/bin/env node
/**
 * Generates the thorax muscle parameter set: the intercostals.
 *
 *   pnpm generate:thorax-muscles          # rewrite packages/muscle-data/src/thorax.ts
 *   pnpm generate:thorax-muscles --check  # fail if the file is not what this would write
 *
 * ## Where the numbers come from
 *
 * One external and one internal sheet in each of the eleven spaces a side, sized the way Bruno
 * 2015 sized them for the thoracolumbar spine and rib cage model, since no vendored actuator
 * exists for them: a sheet's cross-section is the rib's length, tubercle to anterior end,
 * times its 2.5 mm thickness; its optimal fibre length is the distance between its attachments
 * on the two ribs; pennation is nothing, the tendon is a tenth of a millimetre, and force is
 * cross-section at 100 N/cm². The rib lengths are this project's, measured along each rib's
 * arc (`rib-arcs.json`), and a space takes the mean of its two ribs'.
 */

import { readFileSync, writeFileSync } from 'node:fs';
import { join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';
import { distance, renderMuscleGroups } from '../lib/renderMuscles.mjs';

const ROOT = fileURLToPath(new URL('../../..', import.meta.url));
const OUT = join(ROOT, 'packages/muscle-data/src/thorax.ts');
const DATA = join(ROOT, 'packages/assets-anatomical/data');
const check = process.argv.includes('--check');

const landmarks = JSON.parse(readFileSync(join(DATA, 'landmarks.json'), 'utf8'));
const arcs = JSON.parse(readFileSync(join(DATA, 'rib-arcs.json'), 'utf8')).ribs;

/** Bruno 2015: a sheet's thickness, m; its stress, N/cm²; its tendon, m. */
const SHEET_THICKNESS = 0.0025;
const MAX_MUSCLE_STRESS = 100;
const TENDON = 0.0001;

const SHEETS = [
  {
    sheet: 'external',
    groupName: 'Intercostales externi',
    taTerm: 'Musculi intercostales externi',
    from: 'Lower_border_at_50',
  },
  {
    sheet: 'internal',
    groupName: 'Intercostales interni',
    taTerm: 'Musculi intercostales interni',
    from: 'Lower_border_at_70',
  },
];

function render() {
  const groups = [];
  for (const s of ['r', 'l']) {
    for (const { sheet, groupName, taTerm, from } of SHEETS) {
      const units = [];
      for (let n = 1; n <= 11; n++) {
        const above = `rib_${n}_${s}`;
        const below = `rib_${n + 1}_${s}`;
        const origin = landmarks[above]?.[from];
        const insertion = landmarks[below]?.Upper_border_at_60;
        const length = (arcs[above].arcLength + arcs[below].arcLength) / 2;
        if (!origin || !insertion) throw new Error(`no rib points for space ${n} ${s}`);
        const fibre = distance(origin, insertion);
        const pcsaCm2 = length * 100 * (SHEET_THICKNESS * 100);
        const id = `${sheet}_intercostal_${n}`;
        units.push({
          id: `${id}_${s}`,
          displayName: `${sheet === 'external' ? 'External' : 'Internal'} intercostal, space ${n}, ${s === 'r' ? 'right' : 'left'}`,
          origin: `${id}_origin_${s}_${from.toLowerCase()}`,
          insertion: `${id}_insertion_${s}_upper_border_at_60`,
          path: [],
          parameters: {
            maxIsometricForce: MAX_MUSCLE_STRESS * pcsaCm2,
            optimalFiberLength: fibre,
            tendonSlackLength: TENDON,
            pennationAngle: 0,
          },
          source: {
            call: 'bruno',
            args: [
              String(n),
              String(Number((length * 1000).toFixed(1))),
              String(Number((fibre * 1000).toFixed(1))),
            ],
          },
        });
      }
      groups.push({
        id: `${sheet}_intercostals_${s}`,
        displayName: `${groupName}, ${s === 'r' ? 'right' : 'left'}`,
        taTerm,
        innervation: 'Intercostal nerves',
        source: `gray('${groupName}')`,
        units,
      });
    }
  }
  const body = renderMuscleGroups(groups);

  return `/**
 * The thorax muscle parameter set -- the intercostals, which hold the ribs to one another.
 *
 * **Generated by \`pnpm generate:thorax-muscles\`. Do not edit.** CI runs the generator with
 * \`--check\`.
 *
 * An external and an internal sheet in each of the eleven spaces a side, from a rib's lower
 * border to the upper border of the rib below, the external running forward and down and the
 * internal back and down. No vendored actuator exists for them; they are sized by Bruno 2015's
 * rule on this project's own ribs: cross-section as rib length times a 2.5 mm sheet, fibre
 * length as the distance between the attachments, force at 100 N/cm².
 */

import { cite } from '@bs-humany/hsdl';
import type { MuscleGroup } from './schema.js';

/** Anatomy: which bony feature a muscle attaches to. The sites themselves are cited in M5.3. */
const gray = (muscle: string) => cite('gray1918', \`Part IV, Myology: The \${muscle}\`);

/** Parameters: Bruno 2015's sizing rule, with this space's rib length and attachment distance. */
const bruno = (space: number, ribLengthMm: number, fibreMm: number) =>
  cite(
    'bruno2015',
    'intercostal PCSA as rib length x 2.5 mm a sheet, fibre length as the attachment distance, ' +
      \`tendon 0.1 mm, 100 N/cm²; space \${space}: mean rib length \${ribLengthMm} mm (rib-arcs.json), \` +
      \`\${fibreMm} mm between attachments\`,
  );

export const THORAX_MUSCLES: readonly MuscleGroup[] = [
${body}
];

/** Every unit in the set, flattened, in a stable order. */
export const THORAX_UNITS = THORAX_MUSCLES.flatMap((g) => g.units);
`;
}

const text = render();
if (check) {
  const current = readFileSync(OUT, 'utf8');
  if (current !== text) {
    console.error(`${relative(ROOT, OUT)} is stale; run pnpm generate:thorax-muscles`);
    process.exit(1);
  }
  console.log(`${relative(ROOT, OUT)} is up to date`);
} else {
  writeFileSync(OUT, text);
  console.log(`wrote ${relative(ROOT, OUT)}`);
}
